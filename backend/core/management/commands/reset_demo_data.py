import os
from django.conf import settings
from django.core.management import call_command
from django.core.management.base import BaseCommand
from django.db import transaction

from accounts.models import User
from bookings.models import Booking, BusSchedule
from drivers.models import Driver
from notifications.models import Notification
from payments.models import Payment, Receipt
from trips.models import Trip, TripLocation
from vehicles.models import Vehicle, Maintenance


class Command(BaseCommand):
    help = "Resets demo data (deletes seeded and test records, preserves real superuser and Payment QR, then reseeds)."

    def add_arguments(self, parser):
        parser.add_argument(
            "--no-input",
            "--yes",
            action="store_true",
            help="Bypass interactive confirmation prompt.",
        )

    def handle(self, *args, **options):
        if not settings.DEBUG:
            self.stdout.write(
                self.style.ERROR("Error: reset_demo_data can ONLY be run when DEBUG is True.")
            )
            return

        if not options.get("no_input"):
            self.stdout.write(
                self.style.WARNING(
                    "WARNING: This will delete all demo and test bookings, trips, payments, vehicles, and demo users."
                )
            )
            try:
                confirm = input("Type 'yes' to continue: ")
            except EOFError:
                confirm = "no"

            if confirm.strip().lower() != "yes":
                self.stdout.write(self.style.NOTICE("Reset cancelled."))
                return

        self.stdout.write(self.style.NOTICE("Resetting demo data..."))

        demo_emails = [
            "admin@fleetflow.com",
            "manager@fleetflow.com",
            "driver1@fleetflow.com",
            "driver2@fleetflow.com",
            "driver3@fleetflow.com",
            "customer1@fleetflow.com",
            "customer2@fleetflow.com",
            "customer3@fleetflow.com",
            "customer4@fleetflow.com",
            "customer5@fleetflow.com",
        ]

        with transaction.atomic():
            # Find demo users and test users (excluding real superusers who are not admin@fleetflow.com)
            from django.db.models import Q
            demo_users_qs = User.objects.filter(
                email__in=demo_emails
            ) | User.objects.filter(
                email__endswith="@fleetflow.com"
            ).exclude(
                Q(is_superuser=True) & ~Q(email="admin@fleetflow.com")
            )

            # Also include any test users generated by test runs
            test_users_qs = User.objects.filter(
                email__istartswith="test"
            ) | User.objects.filter(
                email__icontains="e2e"
            ) | User.objects.filter(
                email__istartswith="demo_temp"
            )

            all_target_users = (demo_users_qs | test_users_qs).distinct()
            user_ids = list(all_target_users.values_list("id", flat=True))

            # 1. Receipts & Payments (Receipt linked via CASCADE to Payment, but clean explicitly)
            Receipt.objects.filter(payment__customer_id__in=user_ids).delete()
            Receipt.objects.all().delete()
            Payment.objects.all().delete()

            # 2. Trip Locations & Trips
            TripLocation.objects.all().delete()
            Trip.objects.all().delete()

            # 3. Bookings & Bus Schedules
            Booking.objects.all().delete()
            BusSchedule.objects.all().delete()

            # 4. Maintenance & Vehicles
            Maintenance.objects.all().delete()
            Vehicle.objects.all().delete()

            # 5. Notifications
            Notification.objects.filter(user_id__in=user_ids).delete()

            # 6. Drivers
            Driver.objects.filter(user_id__in=user_ids).delete()

            # 7. Demo and test users (leaves real superuser completely untouched)
            all_target_users.delete()

            self.stdout.write(self.style.SUCCESS("Cleaned up demo and test records (Payment QR settings and real superuser preserved)."))

        # Re-run seed_demo_data to populate fresh demo records
        self.stdout.write(self.style.NOTICE("Re-seeding fresh demo data..."))
        call_command("seed_demo_data")
        self.stdout.write(self.style.SUCCESS("Demo data successfully reset and reseeded."))
