def generate_pdf_document(doc_type_label, doc_number, expiry_date):
    buffer = io.BytesIO()
    p = canvas.Canvas(buffer, pagesize=letter)
    p.setTitle(f"{doc_type_label} - {doc_number}")
    p.setFont("Helvetica-Bold", 18)
    p.drawString(72, 720, "FleetFlow Official Compliance Document")
    p.setLineWidth(1.5)
    p.setStrokeColorRGB(0.31, 0.27, 0.90)
    p.line(72, 705, 540, 705)

    p.setFont("Helvetica-Bold", 12)
    p.drawString(72, 660, "Document Type:")
    p.setFont("Helvetica", 12)
    p.drawString(200, 660, str(doc_type_label))

    p.setFont("Helvetica-Bold", 12)
    p.drawString(72, 625, "Document Number:")
    p.setFont("Helvetica", 12)
    p.drawString(200, 625, str(doc_number))

    p.setFont("Helvetica-Bold", 12)
    p.drawString(72, 590, "Expiry Date:")
    p.setFont("Helvetica", 12)
    p.drawString(200, 590, str(expiry_date))

    p.setFont("Helvetica-Bold", 12)
    p.drawString(72, 555, "Verification Status:")
    p.setFont("Helvetica", 12)
    p.drawString(200, 555, "AUTHENTICATED & ACTIVE")

    p.setFont("Helvetica-Oblique", 10)
    p.drawString(72, 490, "Generated by FleetFlow Fleet Management System.")
    p.drawString(72, 475, "This is a legally valid digital compliance record.")

    p.showPage()
    p.save()
    buffer.seek(0)
    return buffer.getvalue()


def generate_receipt_png(title, subtitle, amount):
    img = Image.new("RGB", (450, 250), color=(248, 250, 252))
    d = ImageDraw.Draw(img)
    d.rectangle([8, 8, 442, 242], outline=(79, 70, 229), width=2)
    d.rectangle([8, 8, 442, 55], fill=(79, 70, 229))
    d.text((20, 18), "FleetFlow Official Receipt", fill=(255, 255, 255))

    d.text((20, 75), f"Item: {title}", fill=(15, 23, 42))
    d.text((20, 110), f"Details: {subtitle}", fill=(71, 85, 105))
    d.text((20, 145), f"Amount: {amount}", fill=(15, 23, 42))
    d.text((20, 190), "Status: PAID / VERIFIED", fill=(22, 101, 52))

    buffer = io.BytesIO()
    img.save(buffer, format="PNG")
    buffer.seek(0)
    return buffer.getvalue()



